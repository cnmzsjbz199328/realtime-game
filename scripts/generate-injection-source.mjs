/**
 * Generates core/runtime/std/InjectionSource.ts from Vector.ts and RetroAudio.ts.
 * Run manually: npm run generate-injection
 * Runs automatically as prebuild.
 */
import { readFileSync, writeFileSync } from 'fs';
import { transform } from 'esbuild';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dir = dirname(fileURLToPath(import.meta.url));
const root = join(__dir, '..');

async function toPlainJS(filePath) {
    const src = readFileSync(filePath, 'utf-8');
    const { code } = await transform(src, { loader: 'ts', target: 'es2022' });
    return code
        .replace(/^export \{[^}]*\};\s*$/m, '')                          // strip trailing export { X };
        .replace(/^export (class|const|function|let|var) /gm, '$1 ')     // strip export keyword
        .trim();
}

// Escape for safe embedding inside a TypeScript template literal
function safe(s) {
    return s
        .replace(/\\/g, '\\\\')
        .replace(/`/g, '\\`')
        .replace(/\$\{/g, '\\${');
}

const vectorJs   = await toPlainJS(join(root, 'core/runtime/std/Vector.ts'));
const retroJs    = await toPlainJS(join(root, 'core/runtime/std/RetroAudio.ts'));

// Build the output file using plain string concat to avoid ambiguous template escaping
const NL = '\n';
const BT = '`';        // backtick  — written into the generated file
const DS = '${';       // ${ sequence — written into the generated file

const output =
    `import { COLORS } from './Colors';` + NL +
    NL +
    `// Auto-generated by scripts/generate-injection-source.mjs — DO NOT EDIT MANUALLY` + NL +
    `// Run \`npm run generate-injection\` to regenerate after modifying Vector.ts or RetroAudio.ts` + NL +
    `export const LIBRARY_SOURCE = ` + BT + NL +
    `const COLORS = ` + DS + `JSON.stringify(COLORS)};` + NL +
    NL +
    safe(vectorJs) + NL +
    NL +
    safe(retroJs) + NL +
    BT + `;` + NL;

writeFileSync(join(root, 'core/runtime/std/InjectionSource.ts'), output, 'utf-8');
console.log('✓ InjectionSource.ts regenerated from Vector.ts + RetroAudio.ts');
